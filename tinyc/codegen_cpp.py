"""tinyc IR -> C++ source (OpenMP). Constants live in one aligned blob passed at init."""
from __future__ import annotations

import numpy as np

from .ir import BINARY, UNARY, Graph
from .passes import plan_memory


def _lit(v: float) -> str:
    return f"{float(np.float32(v)):.9e}f"


def expr_c(t, ref) -> str:
    """Expression tree -> C expression; ref(k) gives the C lvalue of input k at element i."""
    if t[0] == "in":
        return ref(t[1])
    if t[0] == "lit":
        return f"({_lit(t[1])})"
    if t[0] in UNARY:
        return UNARY[t[0]].format(expr_c(t[1], ref))
    return BINARY[t[0]].format(expr_c(t[1], ref), expr_c(t[2], ref))


def pack_consts(g: Graph):
    offs, parts, cur = {}, [], 0
    for name, arr in g.consts.items():
        a = np.ascontiguousarray(arr, np.float32).ravel()
        offs[name] = cur
        pad = (-a.size) % 16
        parts.append(a); parts.append(np.zeros(pad, np.float32))
        cur += a.size + pad
    blob = np.concatenate(parts) if parts else np.zeros(16, np.float32)
    return blob, offs


class _Emitter:
    """Shared by the C++ and CUDA backends: buffer naming and memory plan."""

    def __init__(self, g: Graph, reuse_memory: bool):
        self.g = g
        self.blob, self.coff = pack_consts(g)
        self.buf_of, self.sizes, self.root = plan_memory(g, reuse=reuse_memory)
        self.boff, cur = [], 0
        for s in self.sizes:
            self.boff.append(cur); cur += s + ((-s) % 16)
        self.arena_floats = cur
        self.shape = {n.name: n.shape for n in g.nodes}
        # conv scratch for im2col
        self.scratch = 0
        self.hand_scratch = max([int(np.prod(n.shape)) for n in g.nodes if n.op in ('linear', 'conv2d') and n.attrs.get('hand')] + [16])
        for n in g.nodes:
            if n.op == "conv2d":
                k = n.attrs["k"]
                C = self.shape[n.inputs[0]][1]
                B = self.shape[n.inputs[0]][0]
                self.scratch = max(self.scratch, B * C * k * k * n.shape[2] * n.shape[3])

    def ptr(self, name: str, base_w="W", base_a="arena", base_in="in0", base_out="out0") -> str:
        r = self.root(name)
        if r in self.coff:
            return f"({base_w} + {self.coff[r]})"
        if r in self.g.inputs:
            return base_in
        b = self.buf_of[r]
        return base_out if b < 0 else f"({base_a} + {self.boff[b]})"

    def numel(self, name):
        return int(np.prod(self.shape[name]))


def epilogue_body(n, em: _Emitter, idx: str, ch: str, ptr) -> list[str]:
    lines = []
    for step in n.attrs.get("epilogue", []):
        if step[0] == "unary":
            lines.append(f"v = {UNARY[step[1]].format('v')};")
        else:
            _, op, k, lhs = step
            name = n.inputs[k]
            o = f"{ptr(name)}[0]" if em.numel(name) == 1 else f"{ptr(name)}[{idx}]"
            lines.append(f"v = {BINARY[op].format(o, 'v') if lhs else BINARY[op].format('v', o)};")
    return lines


def generate_cpp(g: Graph, reuse_memory: bool = True) -> tuple[str, np.ndarray, dict]:
    em = _Emitter(g, reuse_memory)
    L = ["// generated by tinyc", '#include "tinyc_runtime.hpp"', "#include <cstdlib>", "",
         "static const float* W = nullptr;", "static float* arena = nullptr;", "static float* scratch = nullptr;", "static float* gemm_tmp = nullptr;", ""]
    L.append(f'extern "C" long tinyc_arena_bytes() {{ return {em.arena_floats * 4}L; }}')
    L.append('extern "C" int tinyc_init(const float* blob) {')
    L.append("  W = blob;")
    L.append(f"  arena = (float*)std::aligned_alloc(64, {max(em.arena_floats, 16) * 4});")
    L.append(f"  scratch = (float*)std::aligned_alloc(64, {max(em.scratch, 16) * 4 + 64});")
    L.append(f"  gemm_tmp = (float*)std::aligned_alloc(64, {((em.hand_scratch + 15) // 16) * 64});")
    L.append("  return arena && scratch && gemm_tmp ? 0 : 1;\n}")
    L.append('extern "C" void tinyc_forward(const float* __restrict in0, float* __restrict out0) {')
    for n in g.nodes:
        if n.op in ("input", "const", "reshape"):
            continue
        y = em.ptr(n.name)
        L.append(f"  // {n.op} -> %{n.name} {list(n.shape)}")
        if n.op == "linear":
            x, w, b = (em.ptr(i) for i in n.inputs[:3])
            M = int(np.prod(em.shape[n.inputs[0]][:-1])); K = em.shape[n.inputs[0]][-1]; N = n.shape[-1]
            body = epilogue_body(n, em, "(size_t)i * %d + j" % N, "j", em.ptr)
            L.append(f"  {{ const float* bias = {b}; float* y = {y};")
            gemm = 'gemm_hand' if n.attrs.get('hand') else 'gemm'
            temporary = 'gemm_tmp, ' if n.attrs.get('hand') else ''
            L.append(f"    tc::{gemm}({temporary}{x}, {w}, {M}, {K}, {N}, [&](int i, int j, float v) {{ v += bias[j]; "
                     + " ".join(body) + f" y[(size_t)i * {N} + j] = v; }}); }}")
        elif n.op == "conv2d":
            x, w, b = (em.ptr(i) for i in n.inputs[:3])
            B, C, H, Wd = em.shape[n.inputs[0]]; _, Co, OH, OW = n.shape
            k, s, p = n.attrs["k"], n.attrs["stride"], n.attrs["pad"]
            P = OH * OW
            # GEMM column j = b*P + pix  ->  NCHW output index b*Co*P + i*P + pix
            idx = f"(size_t)(j / {P}) * {Co * P} + (size_t)i * {P} + (j % {P})"
            body = epilogue_body(n, em, idx, "i", em.ptr)
            L.append(f"  {{ const float* bias = {b}; float* y = {y};")
            L.append(f"    tc::im2col({x}, {B}, {C}, {H}, {Wd}, {k}, {s}, {p}, {OH}, {OW}, scratch);")
            gemm = 'gemm_hand' if n.attrs.get('hand') else 'gemm'
            temporary = 'gemm_tmp, ' if n.attrs.get('hand') else ''
            L.append(f"    tc::{gemm}({temporary}{w}, scratch, {Co}, {C * k * k}, {B * P}, [&](int i, int j, float v) {{ v += bias[i]; "
                     + " ".join(body) + f" y[{idx}] = v; }}); }}")
        elif n.op in ('layernorm', 'softmax'):
            rows, cols = int(np.prod(n.shape[:-1])), n.shape[-1]
            if n.op == 'softmax':
                fn = 'ti_cpu_softmax' if n.attrs.get('hand') else 'tc::softmax'
                L.append(f'  {fn}({em.ptr(n.inputs[0])}, {y}, {rows}, {cols});')
            else:
                fn = 'ti_cpu_layernorm' if n.attrs.get('hand') else 'tc::layernorm'
                L.append(f'  {fn}({em.ptr(n.inputs[0])}, {em.ptr(n.inputs[1])}, {em.ptr(n.inputs[2])}, {y}, {rows}, {cols}, {_lit(n.attrs["eps"])});')
        elif n.op == "batchnorm":
            B, C, H, Wd = n.shape
            x, sc, sh = (em.ptr(i) for i in n.inputs)
            L.append(f"  tc::batchnorm({x}, {B}, {C}, {H * Wd}, {sc}, {sh}, {y});")
        elif n.op == "maxpool2d":
            B, C, H, Wd = em.shape[n.inputs[0]]
            L.append(f"  tc::maxpool2d({em.ptr(n.inputs[0])}, {B}, {C}, {H}, {Wd}, {n.attrs['k']}, {n.attrs['stride']}, "
                     f"{n.shape[2]}, {n.shape[3]}, {y});")
        elif n.op == "fused_ew":
            N = em.numel(n.name)
            ins = [em.ptr(i) for i in n.inputs]
            ref = lambda k: f"p{k}[0]" if em.numel(n.inputs[k]) == 1 else f"p{k}[i]"
            decl = " ".join(f"const float* p{k} = {p};" for k, p in enumerate(ins))
            L.append(f"  {{ {decl} float* y = {y};")
            L.append(f"#pragma omp parallel for simd schedule(static) if ({N} > 16384)")
            L.append(f"    for (long i = 0; i < {N}; ++i) y[i] = {expr_c(n.attrs['tree'], ref)}; }}")
        else:
            raise NotImplementedError(n.op)
    out_r = em.root(g.outputs[0])
    if out_r in em.coff or out_r in g.inputs:   # degenerate graph: output is a constant/input
        L.append(f"  std::memcpy(out0, {em.ptr(out_r)}, {em.numel(g.outputs[0]) * 4});")
    L.append("}")
    info = {"arena_bytes": em.arena_floats * 4, "kernels": g.num_kernels(), "const_bytes": int(em.blob.size * 4)}
    return "\n".join(L) + "\n", em.blob, info
