"""tinyc IR -> CUDA source. Same IR, memory plan and fusion decisions as the C++ backend:
GEMMs (linear, conv2d via im2col) carry generated epilogue functors; fused_ew nodes become one kernel each."""
from __future__ import annotations

import numpy as np

from .codegen_cpp import _Emitter, expr_c
from .ir import BINARY, UNARY, Graph


def generate_cuda(g: Graph, reuse_memory: bool = True) -> tuple[str, np.ndarray, dict]:
    em = _Emitter(g, reuse_memory)
    P = lambda name: em.ptr(name, base_w="dW", base_a="darena", base_in="din", base_out="dout")
    defs, body = [], []
    for n in g.nodes:
        if n.op in ("input", "const", "reshape"):
            continue
        y = P(n.name)
        tag = "".join(ch if ch.isalnum() else "_" for ch in n.name)
        body.append(f"  // {n.op} -> %{n.name} {list(n.shape)}")
        if n.op in ("linear", "conv2d"):
            extra = n.inputs[3:]
            members = ["const float* bias;", "float* y;"] + [f"const float* e{k};" for k in range(len(extra))]
            if n.op == "linear":
                N = n.shape[-1]
                idx, bias_ix, ystore = f"(size_t)i * {N} + j", "j", f"(size_t)i * {N} + j"
            else:
                _, Co, OH, OW = n.shape
                Pp = OH * OW
                idx = f"(size_t)(j / {Pp}) * {Co * Pp} + (size_t)i * {Pp} + (j % {Pp})"
                bias_ix, ystore = "i", idx
            lines = [f"v += bias[{bias_ix}];"]
            for step in n.attrs.get("epilogue", []):
                if step[0] == "unary":
                    lines.append(f"v = {UNARY[step[1]].format('v')};")
                else:
                    _, op, k, lhs = step
                    nm = n.inputs[k]
                    o = f"e{k - 3}[0]" if em.numel(nm) == 1 else f"e{k - 3}[{idx}]"
                    lines.append(f"v = {BINARY[op].format(o, 'v') if lhs else BINARY[op].format('v', o)};")
            defs.append(f"struct Epi_{tag} {{ {' '.join(members)}\n  __device__ void operator()(int i, int j, float v) const {{ "
                        + " ".join(lines) + f" y[{ystore}] = v; }} }};")
            init = ", ".join([P(n.inputs[2]), y] + [P(e) for e in extra])
            if n.op == "linear":
                x, w = P(n.inputs[0]), P(n.inputs[1])
                M = int(np.prod(em.shape[n.inputs[0]][:-1])); K = em.shape[n.inputs[0]][-1]
                body.append(f"  tc::gemm({x}, {w}, {M}, {K}, {N}, Epi_{tag}{{{init}}});")
            else:
                B, C, H, Wd = em.shape[n.inputs[0]]
                k, s, p = n.attrs["k"], n.attrs["stride"], n.attrs["pad"]
                body.append(f"  tc::im2col_k<<<tc::blocks({B * C * k * k * Pp}), 256>>>({P(n.inputs[0])}, {B}, "
                            f"{C}, {H}, {Wd}, {k}, {s}, {p}, {OH}, {OW}, dscratch);")
                body.append(f"  tc::gemm({P(n.inputs[1])}, dscratch, {Co}, {C * k * k}, {B * Pp}, Epi_{tag}{{{init}}});")
        elif n.op == "batchnorm":
            B, C, H, Wd = n.shape
            ne = B * C * H * Wd
            body.append(f"  tc::batchnorm_k<<<tc::blocks({ne}), 256>>>({P(n.inputs[0])}, {ne}, {C}, {H * Wd}, "
                        f"{P(n.inputs[1])}, {P(n.inputs[2])}, {y});")
        elif n.op == "maxpool2d":
            B, C, H, Wd = em.shape[n.inputs[0]]
            ne = B * C * n.shape[2] * n.shape[3]
            body.append(f"  tc::maxpool_k<<<tc::blocks({ne}), 256>>>({P(n.inputs[0])}, {B * C}, {H}, {Wd}, {n.attrs['k']}, "
                        f"{n.attrs['stride']}, {n.shape[2]}, {n.shape[3]}, {y});")
        elif n.op == "fused_ew":
            ne = em.numel(n.name)
            params = ", ".join(f"const float* __restrict__ p{k}" for k in range(len(n.inputs)))
            ref = lambda k: f"p{k}[0]" if em.numel(n.inputs[k]) == 1 else f"p{k}[i]"
            defs.append(f"__global__ void ew_{tag}({params}{', ' if params else ''}float* __restrict__ y) {{\n"
                        f"  const long i = blockIdx.x * (long)blockDim.x + threadIdx.x;\n"
                        f"  if (i < {ne}) y[i] = {expr_c(n.attrs['tree'], ref)};\n}}")
            args = ", ".join([P(i) for i in n.inputs] + [y])
            body.append(f"  ew_{tag}<<<tc::blocks({ne}), 256>>>({args});")
        else:
            raise NotImplementedError(n.op)

    in_n = int(np.prod(em.shape[g.inputs[0]]))
    out_n = em.numel(g.outputs[0])
    src = f"""// generated by tinyc (CUDA backend)
#include "tinyc_cuda_runtime.cuh"

static float *dW = nullptr, *darena = nullptr, *dscratch = nullptr, *din = nullptr, *dout = nullptr;

{chr(10).join(defs)}

static void run_graph() {{
{chr(10).join(body)}
}}

extern "C" long tinyc_arena_bytes() {{ return {em.arena_floats * 4}L; }}
extern "C" int tinyc_init(const float* blob) {{
  TC_CHECK(cudaMalloc(&dW, {em.blob.size * 4}));
  TC_CHECK(cudaMemcpy(dW, blob, {em.blob.size * 4}, cudaMemcpyHostToDevice));
  TC_CHECK(cudaMalloc(&darena, {max(em.arena_floats, 16) * 4}));
  TC_CHECK(cudaMalloc(&dscratch, {max(em.scratch, 16) * 4}));
  TC_CHECK(cudaMalloc(&din, {in_n * 4}));
  TC_CHECK(cudaMalloc(&dout, {out_n * 4}));
  return 0;
}}
extern "C" int tinyc_forward(const float* in0, float* out0) {{
  TC_CHECK(cudaMemcpy(din, in0, {in_n * 4}, cudaMemcpyHostToDevice));
  run_graph();
  TC_CHECK(cudaGetLastError());
  TC_CHECK(cudaMemcpy(out0, dout, {out_n * 4}, cudaMemcpyDeviceToHost));
  return 0;
}}
// average device time per forward (input already resident), measured with CUDA events
extern "C" float tinyc_bench(int iters) {{
  for (int i = 0; i < 10; ++i) run_graph();
  cudaEvent_t a, b; cudaEventCreate(&a); cudaEventCreate(&b);
  cudaEventRecord(a);
  for (int i = 0; i < iters; ++i) run_graph();
  cudaEventRecord(b); cudaEventSynchronize(b);
  float ms = 0; cudaEventElapsedTime(&ms, a, b);
  return ms / iters;
}}
"""
    return src, em.blob, {"arena_bytes": em.arena_floats * 4, "kernels": g.num_kernels()}
